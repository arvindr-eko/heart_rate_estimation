"""Emit autocorr_templates.h / autocorr_templates_detrended.h (int8, scale 127, 80-bin) from a new_templates*.npz."""
import sys, numpy as np
npz, outdir = sys.argv[1], sys.argv[2]
d = np.load(npz, allow_pickle=True)
bk = [int(b) for b in d["buckets"] if f"template_raw80_{int(b)}" in d]
Q = 127.0
def q(c):
    v = np.round(np.asarray(c) * Q).astype(np.int64); assert v.min() >= -128 and v.max() <= 127; return v
def table(name, tag):
    L = [f"static const int8_t {name}[TEMPLATE_MATCH_N_BUCKETS][TEMPLATE_MATCH_N_CURVE] = {{"]
    for b in bk:
        L.append(f"    /* {b} bpm */ {{" + ", ".join(str(int(x)) for x in q(d[f'template_{tag}_{b}'])) + "},")
    L.append("};"); return L
src = {b: str(d[f"source_{b}"]) for b in bk}
hdr = ["/* AUTO-GENERATED by retune_2026-10/gen_headers.py from " + npz.split("\\")[-1] + " -- DO NOT EDIT BY HAND.",
       " * 34-bucket set (2026-10-12 retune): nearest-5bpm buckets 40..200 plus ONE merged 30-40bpm bucket nominally",
       " * centered 35. Buckets <45bpm (and 200) use the all-valid-ticks (B) selection; others the correct-raw-candidate (A)",
       " * selection (same as the 45-190 templates before). Built from the TRAIN split only (see split.csv).",
       " * ac_lo=20, S_LEN=80 (first 80 bins of v0.15's 126-bin curve), int8 scale 127. */", "",
       "#define TEMPLATE_MATCH_AC_LO 20", "#define TEMPLATE_MATCH_N_CURVE 80", f"#define TEMPLATE_MATCH_N_BUCKETS {len(bk)}",
       "#define TEMPLATE_MATCH_QUANT_SCALE 127.0f", "",
       "static const float kTemplateBpm[TEMPLATE_MATCH_N_BUCKETS] = {", "    " + ", ".join(f"{b}.0f" for b in bk), "};", ""]
open(outdir + "/autocorr_templates.h", "w").write("\n".join(hdr + table("kTemplateCurve", "raw80") + [""]) + "\n")
open(outdir + "/autocorr_templates_detrended.h", "w").write(
    "/* AUTO-GENERATED (retune_2026-10/gen_headers.py) -- detrended companion of autocorr_templates.h, same buckets/order. */\n\n"
    + "\n".join(table("kTemplateCurveDetrended", "det80")) + "\n")
print(len(bk), "buckets ->", outdir)
